#pragma once

#include <ros/ros.h>
#include <memory>
#include <string>

namespace ag_client {

struct Target {
    std::string mission_id;
    std::string label;
    double latitude{0.0};
    double longitude{0.0};
};

struct Options {
    std::string command_topic{"/air_ground/command"};
    std::string state_topic{"/air_ground/state"};
    double state_timeout{5.0};
    double state_max_age{2.0};
    double execution_max_age{2.0};
    double connect_timeout{3.0};
    double receipt_timeout{3.0};
};

// Nonblocking, single-target dispatcher. Owns a private callback queue/spinner.
// submitTarget only queues intent; acceptance/execution/completion are logged
// asynchronously. It never starts MAVROS, changes flight mode or releases hold.
class Client {
public:
    explicit Client(const Options& options = Options());
    ~Client();
    Client(const Client&) = delete;
    Client& operator=(const Client&) = delete;

    // True means queued, or already queued for this mission/label. No retry or
    // new command is generated by duplicate QR heartbeats. False is local busy
    // or invalid input; the caller may try enqueueing again on a later callback.
    bool submitTarget(const Target& target, std::string* reason = nullptr);

private:
    class Impl;
    std::unique_ptr<Impl> impl_;
};

}  // namespace ag_client
